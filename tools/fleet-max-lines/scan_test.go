func TestDirectoryBudget(t *testing.T) {
	root := t.TempDir()
	dir := filepath.Join(root, "flat")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	body := strings.Repeat("x\n", 120)
	for _, name := range []string{"a.py", "b.py", "c.py", "d.py", "e.py"} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	nested := filepath.Join(dir, "child")
	if err := os.MkdirAll(nested, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(nested, "small.py"), []byte("x\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	hits, err := scan(root)
	if err != nil {
		t.Fatal(err)
	}
	var dirs int
	for _, hit := range hits {
		if hit.Kind == "dir" && hit.Path == "flat" && hit.Lines == 600 {
			dirs++
		}
		if hit.Kind == "file" {
			t.Fatalf("file under 200 should pass, got %+v", hit)
		}
	}
	if dirs != 1 {
		t.Fatalf("want one flat directory violation, got %+v", hits)
	}
}
