func TestCountLines(t *testing.T) {
	if countLines(nil) != 0 || countLines([]byte("a\nb\n")) != 2 || countLines([]byte("solo")) != 1 {
		t.Fatal("line count")
	}
}

func TestScan(t *testing.T) {
	root := t.TempDir()
	if err := os.MkdirAll(filepath.Join(root, "scripts"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "scripts", "ok.py"), []byte("print(1)\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "scripts", "fat.py"), []byte(strings.Repeat("x\n", sourceLimit+1)), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "scripts", "bad.mjs"), []byte("export {}\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	dep := filepath.Join(root, "node_modules", "pkg")
	if err := os.MkdirAll(dep, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dep, "index.js"), []byte("module.exports = 1\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	logs := filepath.Join(root, "logs")
	if err := os.MkdirAll(logs, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(logs, "scratch.html"), []byte(strings.Repeat("x\n", sourceLimit+1)), 0o644); err != nil {
		t.Fatal(err)
	}
	hits, err := scan(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(hits) != 2 {
		t.Fatalf("want fat.py and bad.mjs, got %+v", hits)
	}
}

func TestScanSkipsGeneratedWatchBundle(t *testing.T) {
	root := t.TempDir()
	staticDir := filepath.Join(root, "src", "server", "static")
	if err := os.MkdirAll(staticDir, 0o755); err != nil {
		t.Fatal(err)
	}
	body := "/** GENERATED by npm run build:watch-css — edit src/server/watch/*.ts only. */\n" + strings.Repeat("x\n", 400)
	if err := os.WriteFile(filepath.Join(staticDir, "viewer-camera.js"), []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
	hits, err := scan(root)
	if err != nil {
		t.Fatal(err)
	}
	for _, h := range hits {
		if h.Kind == "file" && strings.HasSuffix(h.Path, ".js") {
			t.Fatalf("generated bundle should be skipped, got %+v", h)
		}
	}
}

