// Command fleet-max-lines enforces the fleet file ceiling.
// TypeScript, HTML, SCSS, Python, Go, and Kotlin may be at most 200 lines.
// JavaScript and MJS may not contain any lines: a hit means the file should not exist.
package main

import (
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

const sourceLimit = 200
const dirLimit = 500

var skipDirs = map[string]bool{
	".git": true, ".worktrees": true, "node_modules": true, "dist": true, "dist-server": true,
	"build": true, ".angular": true, ".gradle": true, "vendor": true, "coverage": true, ".next": true,
	"logs": true, "tmp": true, "worker-dist": true, ".venv": true, "venv": true,
}

// JavaScript and MJS are forbidden as hand-authored fleet source (limit 0).
// Esbuild IIFEs under src/server/static/ with a GENERATED banner are deploy artifacts — skipped.
var limits = map[string]int{
	".ts": sourceLimit, ".html": sourceLimit, ".scss": sourceLimit,
	".py": sourceLimit, ".go": sourceLimit, ".kt": sourceLimit,
	".js": 0, ".mjs": 0,
}

type violation struct {
	Kind  string
	Path  string
	Lines int
	Limit int
	Files int
}

func countLines(b []byte) int {
	if len(b) == 0 {
		return 0
	}
	s := strings.ReplaceAll(string(b), "\r\n", "\n")
	s = strings.ReplaceAll(s, "\r", "\n")
	n := strings.Count(s, "\n")
	if strings.HasSuffix(s, "\n") {
		return n
	}
	return n + 1
}

func isGeneratedFleetJS(content []byte) bool {
	if len(content) == 0 {
		return false
	}
	head := content
	if len(head) > 4096 {
		head = head[:4096]
	}
	s := string(head)
	if strings.Contains(s, "GENERATED by npm run build:watch-css") {
		return true
	}
	return strings.Contains(s, "GENERATED — do not edit") && strings.Contains(s, "serviceBindings")
}

// Documented fleet public injectors (USER-APP-DATA.md) — not hand-authored app source.
func isDocumentedFleetInjector(rel string) bool {
	return rel == "public/dryl-user-data.js"
}

func skipForbiddenJS(rel string, content []byte) bool {
	if isDocumentedFleetInjector(rel) {
		return true
	}
	return isGeneratedFleetJS(content)
}

func scan(root string) ([]violation, error) {
	var out []violation
	dirLines := map[string]int{}
	dirFiles := map[string]int{}
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if skipDirs[d.Name()] {
				return fs.SkipDir
			}
			return nil
		}
		if d.Type()&os.ModeSymlink != 0 {
			return nil
		}
		ext := strings.ToLower(filepath.Ext(d.Name()))
		limit, ok := limits[ext]
		if !ok {
			return nil
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		lines := countLines(b)
		if limit == 0 && (skipForbiddenJS(rel, b) || isAndroidEstimatorArtifact(root, rel, b)) {
			return nil
		}
		if lines > limit {
			out = append(out, violation{Kind: "file", Path: rel, Lines: lines, Limit: limit})
		}
		if limit > 0 {
			dir := filepath.ToSlash(filepath.Dir(rel))
			dirLines[dir] += lines
			dirFiles[dir]++
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	for dir, total := range dirLines {
		if total > dirLimit {
			out = append(out, violation{Kind: "dir", Path: dir, Lines: total, Limit: dirLimit, Files: dirFiles[dir]})
		}
	}
	return out, nil
}
